# (its serialisers are imported, so both maps' data read the same).
# Run: python3 tools/levelcheck/plans/afterhours_emit_layout.py                    (writes both .gd files)
#      python3 tools/levelcheck/plans/afterhours_emit_layout.py --stdout [--content] (prints one)
#      python3 tools/levelcheck/plans/afterhours_emit_layout.py --check              (exit 1 if the plan check fails or a
#                                                                                   file is stale)
# Deterministic: plain lists in source order, fixed float formatting. Never hand-edit the output.
