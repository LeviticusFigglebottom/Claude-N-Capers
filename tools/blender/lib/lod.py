"""LOD policy (style guide §5). Pure Python, plus one optional Blender helper.

Decision (C1-01): **LODs are generated by Godot's scene importer** (``meshes/generate_lods=true``,
on by default and written explicitly into every ``.glb.import`` by build.py). Asset scripts export
LOD0 only. Godot's mesh optimizer produces better LOD chains than a Blender decimate and keeps the
.glb small. Small and medium props additionally get ``visibility_range_end`` set by whoever places
them (≤ 25 m clutter, ≤ 60 m medium props).

``decimate_lod()`` exists for the rare case where a hand-tuned LOD is needed (a hero prop whose
silhouette breaks under the auto-LOD). Godot imports meshes named ``<name>_LOD1`` etc. as separate
nodes, so a manual LOD must then be wired with ``visibility_range_*`` by the scene that uses it.
"""

from __future__ import annotations

# Import parameters build.py writes into each generated ``.glb.import`` [params] section.
GODOT_IMPORT_PARAMS: dict[str, str] = {
    "meshes/generate_lods": "true",
    "meshes/ensure_tangents": "true",
    "meshes/create_shadow_meshes": "true",
}

VISIBILITY_RANGE_END = {"clutter": 25.0, "medium": 60.0}


def decimate_lod(obj, ratio: float, suffix: str = "_LOD1"):
    """Duplicate mesh object ``obj`` as ``<name><suffix>`` with a collapse-decimate at ``ratio``.

    Only call this from inside Blender. Returns the new object (modifier left unapplied; the
    exporter applies it)."""
    dup = obj.copy()
    dup.data = obj.data.copy()
    dup.name = obj.name + suffix
    dup.data.name = obj.data.name + suffix
    for coll in obj.users_collection:
        coll.objects.link(dup)
    mod = dup.modifiers.new("Decimate", "DECIMATE")
    mod.decimate_type = "COLLAPSE"
    mod.ratio = max(0.01, min(1.0, ratio))
    mod.use_collapse_triangulate = True
    return dup
